  var LANGS = ['zh', 'en', 'es', 'ja', 'ko', 'vi'];
  var cache = {};
  var lang = 'zh';

  function table(l) {
    if (cache[l]) { return cache[l]; }
    var base = dict[l] || {};
    var extra = (WN.I18N_EXTRA && WN.I18N_EXTRA[l]) || {};
    var merged = {};
    var k;
    for (k in dict.zh) { if (dict.zh.hasOwnProperty(k)) { merged[k] = dict.zh[k]; } }
    for (k in base) { if (base.hasOwnProperty(k)) { merged[k] = base[k]; } }
    for (k in extra) { if (extra.hasOwnProperty(k)) { merged[k] = extra[k]; } }
    cache[l] = merged;
    return merged;
  }

  var i18n = {
    LANGS: LANGS,
    get lang() { return lang; },
    setLang: function (l) {
      if (LANGS.indexOf(l) < 0) { return lang; }
      lang = l;
      return lang;
    },
    /** 语言是否真的可用（es/ja/ko 需要额外字典） */
    available: function (l) {
      if (l === 'zh' || l === 'en') { return true; }
      return !!(WN.I18N_EXTRA && WN.I18N_EXTRA[l]);
    },
    t: function (key, vars) {
      var t = table(lang);
      var s = t[key];
      if (s === undefined) { s = table('zh')[key]; }
      if (s === undefined) { s = dict.en[key]; }
      if (s === undefined) { return key; }
      if (vars) {
        s = s.replace(/\{(\w+)\}/g, function (m, k) {
          return vars[k] !== undefined ? String(vars[k]) : m;
        });
      }
      return s;
    },
    has: function (key) { return table(lang)[key] !== undefined; }
  };

